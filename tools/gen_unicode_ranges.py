"""
Generates src/tokenizer/unicode_ranges.h: the code point ranges of the \\p{L} (letter)
and \\p{N} (number) classes used by GPT-2's pre-tokenization regex.

Run from the repo root: python tools/gen_unicode_ranges.py
"""

import sys
import unicodedata

OUT_FILE = "./src/tokenizer/unicode_ranges.h"
RANGES_PER_LINE = 4


def ranges_where(predicate):
    ranges = []
    start = None

    for cp in range(sys.maxunicode + 2):
        inside = cp <= sys.maxunicode and predicate(unicodedata.category(chr(cp)))

        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            ranges.append((start, cp - 1))
            start = None

    return ranges


def format_table(name, comment, ranges):
    lines = [f"// {comment}", f"static const uint32_t {name}[][2] = {{"]

    for i in range(0, len(ranges), RANGES_PER_LINE):
        row = ", ".join(f"{{0x{lo:05X}, 0x{hi:05X}}}" for lo, hi in ranges[i: i + RANGES_PER_LINE])
        lines.append(f"    {row},")

    lines.append("};")
    return "\n".join(lines)


def main():
    letters = ranges_where(lambda cat: cat.startswith("L"))
    numbers = ranges_where(lambda cat: cat.startswith("N"))

    header = "\n\n".join([
        "#pragma once\n\n"
        f"// Generated by tools/gen_unicode_ranges.py from Unicode {unicodedata.unidata_version}. Do not edit.\n"
        "// Sorted, non-overlapping, inclusive code point ranges.\n\n"
        "#include <cstdint>",
        format_table("LETTER_RANGES", "\\p{L}: Lu Ll Lt Lm Lo", letters),
        format_table("NUMBER_RANGES", "\\p{N}: Nd Nl No", numbers),
    ]) + "\n"

    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)

    print(f"wrote {len(letters)} letter and {len(numbers)} number ranges -> {OUT_FILE}")


if __name__ == "__main__":
    main()
